// Accessibility (ARIA) Module

#[derive(Debug, Clone)]
pub struct AriaAttributes {
    pub role: Option<AriaRole>,
    pub label: Option<String>,
    pub labelled_by: Option<String>,
    pub described_by: Option<String>,
    pub hidden: bool,
    pub live: Option<AriaLive>,
    pub atomic: bool,
    pub relevant: Option<String>,
    pub busy: bool,
    pub disabled: bool,
    pub expanded: Option<bool>,
    pub pressed: Option<bool>,
    pub selected: Option<bool>,
    pub checked: Option<AriaChecked>,
    pub level: Option<u32>,
    pub value_now: Option<f32>,
    pub value_min: Option<f32>,
    pub value_max: Option<f32>,
    pub value_text: Option<String>,
    pub controls: Option<String>,
    pub owns: Option<String>,
    pub flow_to: Option<String>,
    pub active_descendant: Option<String>,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum AriaRole {
    Alert,
    AlertDialog,
    Application,
    Article,
    Banner,
    Button,
    Cell,
    Checkbox,
    ColumnHeader,
    Combobox,
    Complementary,
    ContentInfo,
    Definition,
    Dialog,
    Directory,
    Document,
    Feed,
    Figure,
    Form,
    Grid,
    GridCell,
    Group,
    Heading,
    Img,
    Link,
    List,
    ListBox,
    ListItem,
    Log,
    Main,
    Marquee,
    Math,
    Menu,
    MenuBar,
    MenuItem,
    MenuItemCheckbox,
    MenuItemRadio,
    Navigation,
    None,
    Note,
    Option,
    Presentation,
    ProgressBar,
    Radio,
    RadioGroup,
    Region,
    Row,
    RowGroup,
    RowHeader,
    Scrollbar,
    Search,
    SearchBox,
    Separator,
    Slider,
    SpinButton,
    Status,
    Switch,
    Tab,
    Table,
    TabList,
    TabPanel,
    Term,
    TextBox,
    Timer,
    ToolBar,
    ToolTip,
    Tree,
    TreeGrid,
    TreeItem,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum AriaLive {
    Off,
    Polite,
    Assertive,
}

#[derive(Debug, Clone, Copy, PartialEq)]
pub enum AriaChecked {
    True,
    False,
    Mixed,
}

impl Default for AriaAttributes {
    fn default() -> Self {
        AriaAttributes {
            role: None,
            label: None,
            labelled_by: None,
            described_by: None,
            hidden: false,
            live: None,
            atomic: false,
            relevant: None,
            busy: false,
            disabled: false,
            expanded: None,
            pressed: None,
            selected: None,
            checked: None,
            level: None,
            value_now: None,
            value_min: None,
            value_max: None,
            value_text: None,
            controls: None,
            owns: None,
            flow_to: None,
            active_descendant: None,
        }
    }
}

pub fn parse_aria_role(value: &str) -> Option<AriaRole> {
    match value {
        "alert" => Some(AriaRole::Alert),
        "button" => Some(AriaRole::Button),
        "checkbox" => Some(AriaRole::Checkbox),
        "dialog" => Some(AriaRole::Dialog),
        "link" => Some(AriaRole::Link),
        "menu" => Some(AriaRole::Menu),
        "menuitem" => Some(AriaRole::MenuItem),
        "navigation" => Some(AriaRole::Navigation),
        "radio" => Some(AriaRole::Radio),
        "tab" => Some(AriaRole::Tab),
        "textbox" => Some(AriaRole::TextBox),
        _ => None,
    }
}
